def classify_by_keywords(label):
    """Classify a raw string into a category using regex keyword matching.
    Returns the category name, or None if no rule matched.
    Used as a fallback for canonical names not present in OCCUPATION_CATEGORY.
    """
    if not label or pd.isna(label):
        return None
    s = str(label).lower()
    for category, patterns in HEURISTIC_RULES:
        for pat in patterns:
            if re.search(pat, s):
                return category
    return None


