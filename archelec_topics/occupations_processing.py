def normalize_value(value):
    """From the raw cell value, return a sorted list of canonical occupation
    names. Returns [] for NaN or empty cell.
    Splits on ';' to handle multi-occupation cells (e.g. 'journaliste;écrivain').
    """
    if pd.isna(value) or str(value).strip() == "":
        return []
    components = [c.strip() for c in str(value).split(";") if c.strip()]
    canonical = [OCCUPATION_NORMALIZATION.get(c, c) for c in components]
    return sorted(set(canonical))


def get_categories(occupations):
    """From a list of canonical occupation names, return the list of categories.
    For each occupation we first look in OCCUPATION_CATEGORY (exact match);
    if absent, we attempt regex classification on the (raw) name.
    """
    cats = set()
    for occ in occupations:
        if occ in OCCUPATION_CATEGORY:
            cats.add(OCCUPATION_CATEGORY[occ])
        else:
            heuristic = classify_by_keywords(occ)
            cats.add(heuristic if heuristic else "Non classé")
    return [c for c in CATEGORY_ORDER + ["Non classé"] if c in cats]


def get_main_category(categories):
    """List of categories -> single label.
    If the person has 'non mentionné' AND another category, prefer the other.
    Multi-category cells become 'A+B'.
    """
    # Filter out 'Non mentionné' if other categories are present
    non_missing = [c for c in categories if c != "Non mentionné"]
    if non_missing:
        categories = non_missing
    if len(categories) == 0:
        return "Aucun"
    if len(categories) == 1:
        return categories[0]
    return "+".join(categories)


