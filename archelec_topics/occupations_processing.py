def add_occupation_columns(df, source_col="titulaire-profession", top_n_occupations=30):
    """
    Enrich `df` with 3 columns based on `source_col`:
      - df['occupations']           : canonical occupations list (list of str)
      - df['occupation_categories'] : categories list (list of str)
      - df['occupation_category']   : single label (str)

    Returns (df_enriched, occupation_dummies, category_dummies, diagnostic):
      - occupation_dummies  : DataFrame of dummies for the top_n_occupations
      - category_dummies    : DataFrame of dummies for the 12 categories
      - diagnostic          : dict with 'occupation_counts', 'unmapped',
                              'unclassified', 'top_occupations'
    """
    df = df.copy()
    df["occupations"] = df[source_col].apply(normalize_value)
    df["occupation_categories"] = df["occupations"].apply(get_categories)
    df["occupation_category"] = df["occupation_categories"].apply(get_main_category)

    # Global count and top N occupations
    occupation_counts = Counter()
    for occs in df["occupations"]:
        occupation_counts.update(occs)
    top_occupations = [o for o, _ in occupation_counts.most_common(top_n_occupations)]

    # Dummies per occupation
    occupation_dummies = pd.DataFrame(
        {o: df["occupations"].apply(lambda L, o=o: int(o in L)) for o in top_occupations},
        index=df.index,
    )

    # Dummies per category
    category_dummies = pd.DataFrame(
        {c: df["occupation_categories"].apply(lambda L, c=c: int(c in L)) for c in CATEGORY_ORDER},
        index=df.index,
    )

    # Diagnostic
    unmapped = Counter()       # raw component absent from OCCUPATION_NORMALIZATION
    unclassified = Counter()   # canonical occupation absent from OCCUPATION_CATEGORY
                               # AND not caught by HEURISTIC_RULES (= REAL problem)
    for value in df[source_col].dropna():
        for c in str(value).split(";"):
            c = c.strip()
            if not c:
                continue
            canonical = OCCUPATION_NORMALIZATION.get(c, c)
            if c not in OCCUPATION_NORMALIZATION:
                unmapped[c] += 1
            if canonical not in OCCUPATION_CATEGORY:
                if classify_by_keywords(canonical) is None:
                    unclassified[canonical] += 1

    diagnostic = {
        "occupation_counts": occupation_counts,
        "unmapped": unmapped,
        "unclassified": unclassified,
        "top_occupations": top_occupations,
    }
    return df, occupation_dummies, category_dummies, diagnostic


def print_occupation_diagnostic(diagnostic, df):
    oc = diagnostic["occupation_counts"]
    unclassified = diagnostic["unclassified"]

    print(f"Canonical occupations distincts : {len(oc)}")
    print("\nTop 15 occupations :")
    for o, n in oc.most_common(15):
        print(f"  {n:>5}  {o}")

    print("\nOccupation categories (distribution) :")
    print(df["occupation_category"].value_counts().head(15).to_string())

    # HIGH PRIORITY: real problems = canonical occupations with no category
    # AND not caught by regex.
    if unclassified:
        print(f"\n⚠️  Occupations canoniques NON classées en catégorie ({len(unclassified)}) :")
        print("    (à ajouter dans OCCUPATION_CATEGORY ou dans HEURISTIC_RULES)")
        for c, n in unclassified.most_common(30):
            print(f"  {n:>4}  {c}")
    else:
        print("\n✓ Toutes les occupations canoniques sont classées dans une catégorie.")
